// MECHANISM: keyed by the EXACT English string. LanguageContext's t()
// (and the standalone t() in strings.ts) consults this table first
// when the active language is one of the six phased languages; a miss
// falls back to the English string, then Bangla — so nothing ever
// renders blank or a raw key, and no call site needs editing: every
// existing t({ bn, en }) call picks the translation up automatically.
// Tool titles/descriptions/crumbs do NOT live here — they are per-slug
// data in src/lib/toolsMetaI18n.ts (consulted by resolveRouteSeo,
// ToolsDetailPage and the tools hub).
//
// HONESTY: only strings in this table (plus toolsMetaI18n.ts) are
// translated. Everything else on a phased page renders in English
// (the fallback), never in a guessed language. Never claim all 265
// tools are in 8 languages — only the top 20 are phased, and only
// their main labels/buttons, not every helper line.

export type PhasedLang = 'hi' | 'ar' | 'es' | 'pt' | 'fr' | 'id';

export const PHASED_LANGS: readonly PhasedLang[] = ['hi', 'ar', 'es', 'pt', 'fr', 'id'];

export function isPhasedLang(code: string): code is PhasedLang {
  return (PHASED_LANGS as readonly string[]).includes(code);
}

/** Look up a translated UI string. Miss → English → Bangla. Never blank. */
export function phasedString(lang: string, en: string, bn: string): string {
  if (isPhasedLang(lang)) {
    const hit = PHASED_STRINGS[lang][en];
    if (hit) return hit;
    return en || bn;
  }
  return lang === 'bn' ? bn : en || bn;
}

