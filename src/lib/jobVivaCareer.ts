export function parseVivaChecklist(raw: string | null): string[] {
  if (!raw) return [];
  try {
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    const known = new Set(VIVA_DOCUMENT_ITEMS.map((i) => i.id));
    return parsed.filter((v): v is string => typeof v === 'string' && known.has(v));
  } catch {
    return [];
  }
}

export function toggleVivaChecklistItem(checked: string[], id: string): string[] {
  if (checked.includes(id)) return checked.filter((v) => v !== id);
  if (!VIVA_DOCUMENT_ITEMS.some((i) => i.id === id)) return checked;
  return [...checked, id];
}

/** Load the student's intro draft from this device ('' when none). */
export function loadVivaIntroDraft(storage: Pick<Storage, 'getItem'> | null): string {
  if (!storage) return '';
  try {
    return storage.getItem(VIVA_INTRO_DRAFT_KEY) ?? '';
  } catch {
    return '';
  }
}

/** Save the student's intro draft on this device only. */
export function saveVivaIntroDraft(
  storage: Pick<Storage, 'setItem'> | null,
  draft: string,
): void {
  if (!storage) return;
  try {
    storage.setItem(VIVA_INTRO_DRAFT_KEY, draft);
  } catch {
    // Storage full / unavailable: the draft simply is not kept.
  }
}
